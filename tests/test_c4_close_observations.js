"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const core=require("../radar-history-core"),production=require("../final-core-production");
const {resolveFinalOnly}=require("../canonical-score-resolver");
const {append}=require("../scripts/finalize_core_score_history");
const archive=require("../finalized-core-score-snapshots-v1.json");
const obs=require("../data/c4-close-observations-v1.json");
const root={HSRadarHistory:core,HSFinalCoreProduction:production,HSC4Display:{score:v=>v.toFixed(1)}};
vm.runInNewContext(fs.readFileSync(require.resolve("../radar-history-view"),"utf8"),{window:root});
const view=root.HSRadarHistoryView, cutoff="2026-11-12";
const axis=["2026-11-10","2026-11-11","2026-11-12"];
const plain=value=>JSON.parse(JSON.stringify(value));
for(const [symbol,expected] of Object.entries({"0050":["48.1","30.3","37.4"],"00757":["48.4","45.8","47.4"],"00830":["88.5","77.0","79.8"],"00935":["72.6","59.8","70.4"]})){
  const formal=core.scores(archive,symbol,production,()=>true).rows;
  const before=JSON.stringify(formal);
  const rows=view.observationRows(obs,symbol,cutoff);
  const [segment]=view.observationSegments(axis,formal,rows);
  assert.deepEqual(plain(segment.data.map(p=>p.value.toFixed(1))),expected);
  assert.deepEqual(plain(segment.points.map(p=>p.time)),axis.slice(1));
  assert.equal(JSON.stringify(formal),before);
  assert.equal(view.observationSegments(axis,[...formal,{time:axis[1],value:77}],rows)[0].points.length,1);
  assert.equal(view.observationSegments(["2026-11-09",...axis],formal.filter(r=>r.time!==axis[0]),rows)[0].data.length,2);
}
const halt=view.observationRows(obs,"00662",cutoff);
assert.equal(halt.length,2);
assert.ok(halt.every(r=>r.halt&&r.lastFinal===axis[0]&&!Object.hasOwn(r,"value")));
assert.equal(view.observationSegments(axis,[],halt).length,0);
assert.equal(view.observationRows(obs,"009815",cutoff).length,0);
assert.match(view.html("0050"),/radarObservationLegend/);
assert.doesNotMatch(view.html("0050"),/radarCloseObservations/);
console.log("PASS formal anchor + independent observation markers, formal takes precedence, no gap bridging or fabricated suspension scores");
assert.equal(view.observationRows(obs,"0050","2026-11-10").length,0);
assert.equal(view.observationRows(obs,"0050","2026-11-11").length,1);
assert.equal(view.observationRows({...obs,official_final:true},"0050",cutoff).length,0);
assert.equal(view.observationRows({...obs,calculation_timezone:"Asia/Taipei"},"0050",cutoff).length,0);
const altered=structuredClone(obs);
altered.sessions[0].symbols["0050"].score+=1;
altered.sessions[1].symbols["0050"].tier="<script>";
assert.equal(view.observationRows(altered,"0050",cutoff).length,0);
const broken=structuredClone(obs);
broken.sessions[0].source="https://example.com/";
broken.sessions[1].source_sha256="bad";
assert.equal(view.observationRows(broken,"0050",cutoff).length,0);
console.log("PASS malformed provenance, scores, tiers, future dates and incompatible scope cannot render");
assert.deepEqual(core.scores(obs,"0050",production,()=>true).rows,[]);
assert.equal(resolveFinalOnly({finalizedArtifact:obs,targetDate:cutoff,scoreVersion:production.LONG_TERM_CORE_SCORE_VERSION,symbols:["0050","00662","00757","00830","00935"]}),null);
assert.throws(()=>append(archive,obs),/invalid_eod_envelope/);
assert.ok(!view.html("0050").includes("77.0"));
console.log("PASS official chart, canonical resolver and publisher reject the observation artifact");
